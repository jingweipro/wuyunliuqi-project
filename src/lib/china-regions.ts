// 根据省份获取城市列表
export function getCitiesByProvince(province: string): CityData[] {
  const p = CHINA_REGIONS.find(r => r.name === province);
  return p ? p.cities : [];
}

// 根据省份和城市获取区县列表
export function getDistrictsByCity(province: string, city: string): string[] {
  const cities = getCitiesByProvince(province);
  const c = cities.find(ct => ct.name === city);
  return c ? c.districts : [];
}
