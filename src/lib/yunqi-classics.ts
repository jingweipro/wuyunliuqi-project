// 搜索函数
export function searchClassics(query: string): Array<{
  chapter: ClassicChapter;
  section: ClassicSection;
  matchType: 'title' | 'content' | 'explanation' | 'keyword';
}> {
  if (!query.trim()) return [];
  
  const results: Array<{
    chapter: ClassicChapter;
    section: ClassicSection;
    matchType: 'title' | 'content' | 'explanation' | 'keyword';
  }> = [];
  
  const lowerQuery = query.toLowerCase();
  
  for (const chapter of yunqiClassics) {
    for (const section of chapter.sections) {
      // 检查标题匹配
      if (section.title.toLowerCase().includes(lowerQuery)) {
        results.push({ chapter, section, matchType: 'title' });
        continue;
      }
      
      // 检查关键词匹配
      if (section.keywords.some(kw => kw.toLowerCase().includes(lowerQuery))) {
        results.push({ chapter, section, matchType: 'keyword' });
        continue;
      }
      
      // 检查原文匹配
      if (section.content.includes(query)) {
        results.push({ chapter, section, matchType: 'content' });
        continue;
      }
      
      // 检查解释匹配
      if (section.explanation.includes(query)) {
        results.push({ chapter, section, matchType: 'explanation' });
        continue;
      }
    }
  }
  
  return results;
}

// 获取所有关键词
export function getAllKeywords(): string[] {
  const keywords = new Set<string>();
  
  for (const chapter of yunqiClassics) {
    for (const section of chapter.sections) {
      section.keywords.forEach(kw => keywords.add(kw));
    }
  }
  
  return Array.from(keywords).sort();
}
